import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
process.env.RB_DATA_DIR = mkdtempSync(resolve(tmpdir(),'resume-events-test-'));
const {db,migrate}=await import('../src/db.ts');
const {listEvents,saveEvent}=await import('../src/resume/events.ts');
const {changeStage,workspace,saveContact}=await import('../src/resume/workspace.ts');
const {wallTime,toInstant}=await import('../../web/src/eventTime.ts');
migrate();
db.exec(`INSERT INTO application(id,company,role_title,job_description,created_at,updated_at) VALUES(1,'Acme','Engineer','Posting',1,1),(2,'Beta','Manager','Posting',1,1)`);
const a=saveContact({name:'Recruiter'}),b=saveContact({name:'Interviewer'});
for(const c of [a,b]) db.prepare('INSERT INTO application_contact VALUES(?,?,?)').run(1,c,'interviewer');
const input={title:'Panel',type:'interview',dateOnly:false,start:'2026-11-01T01:30:00-07:00',end:'2026-11-01T01:30:00-08:00',timezone:'America/Los_Angeles',participants:[a,b],state:'scheduled'};
const {id}=saveEvent(1,input);
let row=listEvents(1)[0];
assert.equal(row.start,'2026-11-01T08:30:00.000Z');
assert.equal(row.participants.length,2);
assert.equal(row.history.length,1);
assert.throws(()=>saveEvent(2,input),/participants/);
assert.equal(listEvents(2).length,0);
assert.throws(()=>saveEvent(1,{...input,end:'2026-10-01T00:00:00Z'},id));
assert.equal(listEvents(1)[0].history.length,1);
saveEvent(1,{...input,start:'2026-11-05T10:00:00-08:00',end:null,state:'completed'},id);
assert.equal(listEvents(1)[0].state,'completed');
assert.equal(listEvents(1)[0].history.length,2);
assert.equal(workspace(1).stage,null);
const follow=saveEvent(1,{title:'Agreed response',type:'response',dateOnly:true,start:'2020-02-29',timezone:'America/Los_Angeles'});
assert.equal(listEvents().find(e=>e.id===follow.id)?.start,'2020-02-29');
assert.throws(()=>saveEvent(1,{title:'Bad date',type:'deadline',dateOnly:true,start:'2026-02-30',timezone:'UTC'}));
assert.throws(()=>saveEvent(1,{...input,timezone:'Made/Up'}));
assert.throws(()=>toInstant('2026-03-08T02:30','America/Los_Angeles',''),/does not exist/);
assert.throws(()=>toInstant('2026-11-01T01:30','America/Los_Angeles',''),/occurs twice/);
assert.equal(toInstant('2026-11-01T01:30','America/Los_Angeles','earlier'),'2026-11-01T08:30:00.000Z');
assert.equal(toInstant('2026-11-01T01:30','America/Los_Angeles','later'),'2026-11-01T09:30:00.000Z');
assert.equal(wallTime('2026-11-01T08:30:00Z','America/New_York'),'2026-11-01T03:30');
changeStage(1,{stage:'closed',closureReason:'withdrawal',effectiveDate:'2026-11-03'});
assert.equal(listEvents(1).length,2);
assert.equal(listEvents(1).find(e=>e.id===follow.id)?.state,'scheduled');
saveEvent(1,{...input,state:'cancelled'},id);
assert.equal(listEvents(1).find(e=>e.id===id)?.state,'cancelled');
// Reopening the SQLite file must preserve overdue items and event history.
const {DatabaseSync}=await import('node:sqlite');
const {config}=await import('../src/config.ts');
const reopened=new DatabaseSync(config.dbFile);
assert.equal(reopened.prepare('SELECT start FROM application_event WHERE id=?').get(follow.id)?.start,'2020-02-29');
reopened.close();
db.prepare('DELETE FROM application WHERE id=1').run();
assert.equal(listEvents().length,0);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM event_history').get()?.n,0);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM contact').get()?.n,2);
db.close();
console.log('Phase 2A events: persistence, lifecycle, validation, participants, deletion and DST passed.');
